static uint8_t s_addr = SSD1306_ADDR;

static int prv_cmds( const uint8_t * cmds, uint32_t n )
{
    return i2c_write_regs( s_addr, CTRL_CMD, cmds, n );
}

int ssd1306_init( uint8_t addr )
{
    static const uint8_t init_seq[] = {
        0xAE,             /* display off                 */
        0xD5, 0x80,       /* clock divide                */
        0xA8, 0x3F,       /* multiplex = 64              */
        0xD3, 0x00,       /* display offset 0            */
        0x40,             /* start line 0                */
        0x8D, 0x14,       /* charge pump on              */
        0x20, 0x00,       /* horizontal addressing mode  */
        0xA1, 0xC8,       /* segment/COM remap (rotated) */
        0xDA, 0x12,       /* COM pins config             */
        0x81, 0xCF,       /* contrast                    */
        0xD9, 0xF1,       /* pre-charge                  */
        0xDB, 0x40,       /* VCOMH deselect              */
        0xA4, 0xA6,       /* resume RAM, normal polarity */
        0xAF,             /* display on                  */
    };

    s_addr = addr;

    int rc = prv_cmds( init_seq, sizeof( init_seq ) );
    if( rc != I2C_OK ) return rc;

    return ssd1306_clear();
}

static int prv_set_region( uint8_t col0, uint8_t col1, uint8_t page0, uint8_t page1 )
{
    uint8_t cmds[ 6 ] = { 0x21, col0, col1, 0x22, page0, page1 };

    return prv_cmds( cmds, 6 );
}

int ssd1306_clear( void )
{
    static const uint8_t zeros[ 16 ] = { 0 };
    int rc = prv_set_region( 0, 127, 0, 7 );

    if( rc != I2C_OK ) return rc;

    for( int i = 0; i < ( 128 * 8 ) / 16; i++ )
    {
        rc = i2c_write_regs( s_addr, CTRL_DATA, zeros, 16 );
        if( rc != I2C_OK ) return rc;
    }

    return I2C_OK;
}

/* Print a string at character cell (col 0..20, row 0..7). 6 px per char. */
int ssd1306_text( uint8_t col, uint8_t row, const char * s )
{
    uint8_t glyph[ 6 ];
    uint8_t x = ( uint8_t ) ( col * 6u );
    int rc;

    while( *s != '\0' && x <= 122u )
    {
        uint8_t c = ( uint8_t ) *s++;

        if( c < 32u || c > 127u ) c = '?';

        rc = prv_set_region( x, ( uint8_t ) ( x + 5u ), row, row );
        if( rc != I2C_OK ) return rc;

        for( int i = 0; i < 5; i++ )
        {
            glyph[ i ] = font5x7[ ( c - 32u ) * 5u + ( uint32_t ) i ];
        }
        glyph[ 5 ] = 0x00;   /* inter-char gap */

        rc = i2c_write_regs( s_addr, CTRL_DATA, glyph, 6 );
        if( rc != I2C_OK ) return rc;

        x += 6u;
    }

    return I2C_OK;
}
